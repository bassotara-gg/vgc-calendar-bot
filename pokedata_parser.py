import re
from datetime import datetime

URL_RE = re.compile(r"https?://[^\s)>\]]+", re.I)
ID_RE = re.compile(r"/(\d{2}-\d{2}-\d{6})/?(?:[\s\"'>]|$)", re.I)
EVENT_RE = re.compile(r"\b(?:league\s+(?:cup|challenge)|(?:vg\s+)?league\s+(?:cup|challenge)|(?:league\s+(?:cup|challenge))\s+vg|vg\s+(?:cup|challenge))\b", re.I)


def _clean(value):
    return re.sub(r"\s+", " ", str(value or "")).strip()


def _strip_markdown(value):
    value = re.sub(r"\[([^\]]+)\]\([^)]*\)", r"\1", value or "")
    return _clean(value.replace("**", "").replace("__", ""))


def _pokemon_url(value):
    for url in URL_RE.findall(str(value or "")):
        url = url.rstrip(".,)")
        if "pokemon.com" in url.lower() and "play-pokemon-tournaments" in url.lower():
            return url
    return ""


def _event_id(url):
    match = re.search(r"/(\d{2}-\d{2}-\d{6})/?(?:$|[?#\s])", url or "", re.I)
    return match.group(1) if match else ""


def _event_type(value):
    text = _clean(value).casefold()
    match = EVENT_RE.search(text)
    if not match:
        return ""
    return "cup" if "cup" in match.group(0).casefold() else "challenge"


def _field_from_text(text, label):
    match = re.search(
        rf"(?im)^\s*\*?\*?{re.escape(label)}\*?\*?\s*$\n\s*([^\n]+)",
        text or "",
    )
    return _clean(match.group(1)) if match else ""


def _parse_date(value):
    value = _clean(value)
    try:
        return datetime.strptime(value, "%Y-%m-%d").date().isoformat()
    except ValueError:
        return ""


def _make_event(message_id, event_type, name, url, city, region, address, organizer, raw_date):
    url = _pokemon_url(url)
    pokedata_id = _event_id(url)
    event_date = _parse_date(raw_date)
    if not event_type or not pokedata_id or not event_date or not city or not region:
        return None
    return {
        "pokedata_id": pokedata_id,
        "type": event_type,
        "name": _strip_markdown(name) or f"VGC {'Cup' if event_type == 'cup' else 'Challenge'}",
        "date": event_date,
        "city": _clean(city),
        "region": _clean(region),
        "address": _clean(address),
        "organizer": _clean(organizer),
        "url": url,
        "source_message_id": str(message_id),
    }


def _parse_embed(embed, message_id):
    title = _clean(getattr(embed, "title", ""))
    description = _clean(getattr(embed, "description", ""))
    embed_url = _clean(getattr(embed, "url", ""))

    # Depending on the Pokedata webhook version, the event type can be in the
    # embed title, description, author name, or another header-like value.
    author = getattr(embed, "author", None)
    author_name = _clean(getattr(author, "name", "")) if author else ""
    author_url = _clean(getattr(author, "url", "")) if author else ""

    fields = {}
    for field in getattr(embed, "fields", []) or []:
        field_name = _clean(getattr(field, "name", ""))
        field_value = _clean(getattr(field, "value", ""))
        if field_name:
            fields[field_name.casefold()] = field_value

    header_values = [title, description, author_name, embed_url, author_url]
    header_values.extend(fields.keys())
    header_values.extend(fields.values())
    combined_header = "\n".join(x for x in header_values if x)
    event_type = _event_type(combined_header)

    # Pokedata may expose the official tournament URL in embed.url, in the
    # title/description, or in the author URL.
    pokemon_url = (
        _pokemon_url(embed_url)
        or _pokemon_url(title)
        or _pokemon_url(description)
        or _pokemon_url(author_url)
    )
    if not event_type or not pokemon_url:
        return None

    # Discord embeds expose organizer as description in the common Pokedata
    # format. If the description also contains the URL/type header, strip it.
    organizer = description
    organizer = URL_RE.sub("", organizer)
    organizer = EVENT_RE.sub("", organizer)
    organizer = _strip_markdown(organizer)

    # The event name can be the title, description, or a dedicated field.
    # Prefer a title that is not merely the generic Cup/Challenge label.
    name_candidates = [title, description]
    name = ""
    for candidate in name_candidates:
        candidate_clean = URL_RE.sub("", candidate)
        candidate_clean = EVENT_RE.sub("", candidate_clean)
        candidate_clean = _strip_markdown(candidate_clean)
        if candidate_clean and candidate_clean.casefold() not in {"league cup", "league challenge", "cup", "challenge"}:
            name = candidate_clean
            break

    # If the generic type is the title, Pokedata's actual event name is often
    # the description. In that common case keep the description as organizer
    # only when it is actually the organizer; otherwise the title remains the
    # safe fallback generated by _make_event.
    if not name:
        name = title or description

    return _make_event(
        message_id,
        event_type,
        name,
        pokemon_url,
        fields.get("city", ""),
        fields.get("state", ""),
        fields.get("address", ""),
        organizer,
        fields.get("date", ""),
    )

def _parse_text_block(block, message_id):
    # Fallback for older/non-embed Pokedata messages.
    pokemon_url = _pokemon_url(block)
    event_type = _event_type(block)
    if not pokemon_url or not event_type:
        return None

    lines = [x.strip() for x in (block or "").splitlines() if x.strip()]
    header_index = next(
        (i for i, line in enumerate(lines) if EVENT_RE.search(_strip_markdown(line))),
        None,
    )
    name = ""
    organizer = ""
    if header_index is not None:
        candidates = []
        for line in lines[header_index + 1 :]:
            clean = _strip_markdown(line)
            if not clean or _pokemon_url(line):
                continue
            if re.fullmatch(r"(?:country|state|address|date|city)", clean, re.I):
                break
            candidates.append(clean)
        if candidates:
            name = candidates[0]
        if len(candidates) >= 2:
            organizer = candidates[-1]

    return _make_event(
        message_id,
        event_type,
        name,
        pokemon_url,
        _field_from_text(block, "City"),
        _field_from_text(block, "State"),
        _field_from_text(block, "Address"),
        organizer,
        _field_from_text(block, "Date"),
    )


def parse_pokedata_message(message):
    """Return every Cup/Challenge event contained in a Pokedata Discord message."""
    events = []

    # Current Pokedata webhook format: one Discord message can contain multiple embeds.
    for embed in getattr(message, "embeds", []) or []:
        event = _parse_embed(embed, message.id)
        if event:
            events.append(event)

    # Fallback for old/plain-text webhook messages.
    text = getattr(message, "content", "") or ""
    if text:
        events_in_text = []
        # Split on event headers when possible; otherwise try the whole message.
        matches = list(re.finditer(r"(?im)^.*?(?:league\s+(?:cup|challenge)|(?:vg\s+)?league\s+(?:cup|challenge)).*$", text))
        if matches:
            for index, match in enumerate(matches):
                start = match.start()
                end = matches[index + 1].start() if index + 1 < len(matches) else len(text)
                event = _parse_text_block(text[start:end], message.id)
                if event:
                    events_in_text.append(event)
        else:
            event = _parse_text_block(text, message.id)
            if event:
                events_in_text.append(event)
        events.extend(events_in_text)

    unique = {}
    for event in events:
        unique[event["pokedata_id"]] = event
    return list(unique.values())
